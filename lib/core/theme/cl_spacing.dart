/// Casa Lazzarini spacing tokens.
///
/// Based on a 4px baseline grid — all values are multiples of 4.
abstract final class CLSpacing {
  /// 4px — hairline gaps, icon padding.
  static const double xs = 4;

  /// 8px — tight internal spacing.
  static const double sm = 8;

  /// 12px — moderate internal spacing.
  static const double md = 12;

  /// 16px — standard content padding (the base unit).
  static const double base = 16;

  /// 20px — comfortable section spacing.
  static const double lg = 20;

  /// 24px — generous component spacing.
  static const double xl = 24;

  /// 32px — between distinct sections.
  static const double xxl = 32;

  /// 40px — large layout gaps.
  static const double xxxl = 40;

  /// 48px — screen-level structural spacing.
  static const double huge = 48;
}
